"""Sample vendor files to upload in the test run: Peter's chain from the Hinweise document (step 1 = ITSG's real TEEL0 file,
the other steps generated by the rules engine) and the broken variants of tools/make_submissions.

python -m tools.make_vendor_uploads    (run with the full seed, without SPEC_BASELINE)

Writes samples/vendor_uploads/<variant>/TEEL0-<test case>-r<round> and its README.md. Round r goes to round r of
the vendor's test run; the insurer replies come from the platform.
"""

from __future__ import annotations

from pathlib import Path

from kg import get_kb
from tools.make_submissions import SEEDS, build_submissions

OUT = Path(__file__).resolve().parent.parent / "samples" / "vendor_uploads"
NAMES = {"s-itsg-ref": "01-correct-chain"}


def main() -> None:
    kb = get_kb()
    lines = ["# Sample vendor uploads", "",
             "Generated by `python -m tools.make_vendor_uploads` from the Hinweise scenario (Peter Mustermann).",
             "Upload `…-r1` in round 1 of the vendor's test run, `…-r2` in round 2, `…-r3` in round 3.", "",
             "| Folder | Test case | What it is | Expected result |", "|---|---|---|---|"]
    labels = {sid: (labels, rules) for sid, _tc, _c, _m, labels, rules in SEEDS}
    for n, s in enumerate(build_submissions(kb), start=1):
        name = NAMES.get(s.id, f"{n:02d}-{s.id.removeprefix('s-')}")
        folder = OUT / name
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.iterdir():
            old.unlink()
        for fname, text in s.files.items():
            (folder / fname).write_text(text, encoding="utf-8", newline="")
        by_date, rules = labels[s.id]
        result = ", ".join(f"{label} on {day}" for day, label in by_date.items())
        lines.append(f"| `{name}` | {s.test_case_id} | {s.content} | {result}{' (' + ', '.join(rules) + ')' if rules else ''} |")
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(SEEDS)} variants to {OUT}")


if __name__ == "__main__":
    main()
